// Writes src/environments/environment.prod.ts from the API_URL environment variable
// (set it in Vercel → Project → Settings → Environment Variables), e.g.
//   API_URL=https://api.copakapana.com
// If API_URL is not set, the existing environment.prod.ts is left untouched.
import { writeFileSync } from 'node:fs';

const raw = (process.env.API_URL || '').trim().replace(/\/+$/, '');
if (!raw) {
  console.log('[set-env] API_URL not set - keeping src/environments/environment.prod.ts as is');
  process.exit(0);
}
if (!/^https?:\/\//.test(raw)) {
  console.error(`[set-env] API_URL must start with https:// (got "${raw}")`);
  process.exit(1);
}
const file = `// Generated by scripts/set-env.mjs from API_URL at build time.
export const environment = {
  production: true,
  apiUrl: '${raw}/api/v1',
  wsUrl: '${raw}',
};
`;
writeFileSync(new URL('../src/environments/environment.prod.ts', import.meta.url), file);
console.log(`[set-env] API -> ${raw}`);
